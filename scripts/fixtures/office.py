"""Independent Office interoperability check. Requires python-docx 1.2 and openpyxl.
Run: python scripts/fixtures/office.py --verify-output <NABSUN_OFFICE_OUTPUT>
Fixtures were generated by these libraries, independently of Nabsun's OOXML code.
"""
import argparse
from pathlib import Path
from docx import Document
from openpyxl import load_workbook

def verify(root):
    created = Document(root / 'created.docx')
    assert [p.text for p in created.paragraphs] == ['Project plan', 'Overview', 'Hello & welcome <everyone>\nSecond line.']
    assert created.paragraphs[1].style.style_id == 'Heading1'
    edited = Document(root / 'edited.docx')
    assert edited.paragraphs[1].text == 'Status: new value'
    assert any(run.bold and 'new value' in run.text for run in edited.paragraphs[1].runs)
    assert edited.tables[0].cell(1, 0).text == 'Research'
    assert edited.sections[0].header.paragraphs[0].text == 'Nabsun confidential'
    assert edited.sections[0].footer.paragraphs[0].text == 'Footer stays'
    assert len(edited.inline_shapes) == 1
    assert edited.paragraphs[-1].text == 'Prepare the final report.'
    new_book = load_workbook(root / 'created.xlsx')
    assert new_book.sheetnames == ['Summary', 'Other sheet']
    new_sheet = new_book['Summary']
    assert new_sheet['B2'].value == 5 and new_sheet['C2'].value is True
    assert new_sheet['D2'].value == '=SUM(B2:B3)' and new_sheet['D2'].data_type == 'f'
    assert new_sheet['E2'].value.startswith('=WEBSERVICE') and new_sheet['E2'].data_type == 's'
    assert new_sheet.freeze_panes == 'A2' and new_sheet['A1'].font.bold
    book = load_workbook(root / 'edited.xlsx')
    sheet = book['Budget']
    assert sheet['B2'].value == 8 and sheet['C2'].value == 4
    assert sheet['D2'].value == '=SUM(B2:C2)' and sheet['I12'].value == 'New note'
    assert sheet['B2'].font.bold and sheet['B2'].number_format == '$#,##0.00'
    assert sheet['B2'].comment.text == 'Keep this comment'
    assert len(sheet._charts) == 1 and 'Expenses' in sheet.tables
    assert 'F10:G10' in sheet.merged_cells
    assert len(sheet.data_validations.dataValidation) == 1
    assert book['Archive']['A1'].value == 'Untouched sheet'
    assert book['Locked'].protection.sheet
    assert book.calculation.fullCalcOnLoad and book.calculation.forceFullCalc
    print('PASS independent python-docx/openpyxl readback: new/edited documents, text, headings, run formatting, tables, images, headers/footers, cell types, formulas, comments, charts, styles and validation')

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--verify-output', required=True, type=Path)
    verify(parser.parse_args().verify_output)
